CREATE TABLE IF NOT EXISTS bot_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_key VARCHAR(256) NOT NULL,
    source_key VARCHAR(512) NOT NULL,
    message_role VARCHAR(16) NOT NULL,
    content VARCHAR(2000) NOT NULL,
    created_at BIGINT NOT NULL,
    UNIQUE (source_key, message_role)
);
CREATE INDEX IF NOT EXISTS bot_history_conversation ON bot_history(conversation_key, id);
CREATE INDEX IF NOT EXISTS bot_history_age ON bot_history(created_at);

CREATE TABLE IF NOT EXISTS bot_event (
    sequence_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    event_key VARCHAR(512) PRIMARY KEY,
    conversation_key VARCHAR(256) NOT NULL,
    instance_name VARCHAR(128) NOT NULL,
    phone_number VARCHAR(15) NOT NULL,
    content VARCHAR(2000) NOT NULL,
    oversized BOOLEAN NOT NULL,
    send_requested BOOLEAN NOT NULL,
    received_at BIGINT NOT NULL,
    event_status VARCHAR(24) NOT NULL
);
CREATE INDEX IF NOT EXISTS bot_event_queue ON bot_event(event_status, sequence_id);
